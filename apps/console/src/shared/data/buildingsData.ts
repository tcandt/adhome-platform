export interface Room {
  id: string;
  code: string; // e.g. 31-01, 31-04, 24-02
  buildingId: string; // bld-lk01-31, bld-lk01-32, bld-lk08-24, bld-lk08-25
  buildingCode: string;
  buildingName: string;
  floor: number; // 0 = Trệt, 1 = Tầng 1, 2 = Tầng 2, 3 = Tầng 3
  floorName: string; // Tầng trệt, Tầng 1, Tầng 2, Tầng 3
  type: 'Studio' | '1PN' | '2PN' | 'Studio view ban công' | 'Căn 2PN mini + PK';
  area: number; // m2
  price: number; // VND/month
  status: 'AVAILABLE' | 'OCCUPIED' | 'HELD' | 'MAINTENANCE';
  // Additional operational alerts (not mutually exclusive with occupancy)
  hasExpiringContract?: boolean;
  hasDebtWarning?: boolean;
  isIncompleteRegistration?: boolean; // Tạm trú chưa hoàn thiện (Homeland feature)
  currentTenant?: {
    name: string;
    phone: string;
    checkInDate: string;
    contractEnd: string;
    depositAmount: number;
    debtAmount: number;
    registrationStatus: 'COMPLETED' | 'INCOMPLETE';
  };
  meterStatus: {
    electricMeterId: string;
    electricLastKwh: number;
    waterLastM3: number;
    hunonicOnline: boolean;
    lastSynced: string;
  };
}

