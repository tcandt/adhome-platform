import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, webkit } from 'playwright';
const base = process.env.ADHOME_UI_URL || 'http://127.0.0.1:5192';
const browser = await (process.env.ADHOME_WEBKIT_LAYOUT === '1' ? webkit.launch({headless:true}) : chromium.launch({channel:'chrome',headless:true}));
await mkdir('.artifacts/room-table-layout', {recursive:true});
try { for (const width of [1440,390,320]) {
  const context = await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const building = {id:'b1',code:'QA',name:'QA BUILDING',status:'ACTIVE',floors:[{id:'f1',floorNumber:1,name:'Tang 1'}],stats:{totalRooms:1,occupiedRooms:1}};
  const invoice = {id:'inv1',invoiceCode:'INV-HD-P25-01-D9A1591A',status:'PAID',totalAmountVnd:4500000,paidAmountVnd:4500000,issuedAt:'2026-11-09',dueDate:'2026-11-09',items:[]};
  const contract = {id:'c1',contractCode:'HD-P25-01',status:'ACTIVE',startDate:'2026-11-01',endDate:'2027-11-01',monthlyRentVnd:4500000,tenant:{fullName:'Nguyễn Đức Tính'},invoices:[invoice],deposits:[{id:'d9a1591a',depositType:'CONTRACT',paidAmountVnd:4500000,receivedAt:'2026-11-09'}]};
  const room = {id:'room-0',buildingId:'b1',buildingCode:'QA',buildingName:building.name,building,floorId:'f1',code:'P25-01',area:25,maxOccupants:4,effectiveElectricRateVnd:3800,effectiveWaterRateVnd:15000,unpaidAmountVnd:0,roomType:'Studio',rentalModel:'ENTIRE_ROOM',listPriceVnd:4500000,occupancyStatus:'OCCUPIED',currentTenant:{fullName:'Nguyễn Đức Tính',phone:'0900000001'},activeContract:contract};
  await page.route('**/api/**', async route => {
    const p = new URL(route.request().url()).pathname;
    if(p.endsWith('/auth/me')) return route.fulfill({json:{ok:true,actor:{id:'qa',orgId:'qa',role:'ADMIN',buildingScopes:['*']}}});
    if(p.endsWith('/bootstrap')) return route.fulfill({json:{ok:true,buildings:[building],rooms:[room],tenants:[]}});
    if(p.includes('/rental-workflow/')) return route.fulfill({json:{ok:true,room,contract}});
    return route.fulfill({json:{ok:true,items:[],occupants:[]}});
  });
  await page.goto(base+'/?module=buildings');
  await page.getByTestId('building-expand-QA').click();
  await page.getByTestId('floor-expand-f1').click();
  await page.getByTestId('room-card-QA-P25-01').click();
  await page.getByRole('tab',{name:'Đặt cọc',exact:true}).click();
  const deposits = page.getByTestId('room-deposits-table');
  await deposits.waitFor();
  assert.equal(await deposits.locator('tbody td').nth(2).locator('span').evaluate(el=>getComputedStyle(el).whiteSpace),'nowrap');
  if(width >= 390) assert.equal(await deposits.locator('tbody td').nth(2).locator('span').evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await page.waitForFunction(()=>document.querySelector('[data-testid="room-modal-tab-deposits"]')?.getAttribute('aria-selected')==='true');
  await page.screenshot({path:`.artifacts/room-table-layout/deposits-${width}.png`});
  await page.getByRole('tab',{name:'Hóa đơn',exact:true}).click();
  const table = page.getByTestId('room-invoices-table');
  await table.waitFor();
  assert.equal(await table.getByRole('button',{name:'In PDF',exact:true}).count(),0);
  assert.equal(await table.getByTitle(invoice.invoiceCode).evaluate(el=>getComputedStyle(el).whiteSpace),'nowrap');
  await table.getByRole('button',{name:`Thao tác hóa đơn ${invoice.invoiceCode}`,exact:true}).click();
  await page.getByText('Xem',{exact:true}).click();
  await page.getByTestId('room-invoice-detail-dialog').waitFor();
  assert.match(await page.getByTestId('room-invoice-detail-dialog').innerText(),new RegExp(invoice.invoiceCode));
  await page.getByRole('button',{name:'Đóng chi tiết hóa đơn',exact:true}).click();
  await table.getByRole('button',{name:`Thao tác hóa đơn ${invoice.invoiceCode}`,exact:true}).click();
  await page.getByText('In PDF',{exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('iframe')].some(el=>el.contentDocument?.title==='INV-HD-P25-01-D9A1591A'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`.artifacts/room-table-layout/invoices-${width}.png`});
  assert.deepEqual(errors,[]);
  await context.close();
} } finally { await browser.close(); }
console.log('PASS deposit/invoice layout and view/print actions at 1440/390/320px');
